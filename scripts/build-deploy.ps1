#Requires -Version 5.1

<#
.SYNOPSIS
    Builds the Silkard server jar and deploys it to <repo>\deploy.

.DESCRIPTION
    Removes every *.jar from the deploy folder, builds the launcher jar with
    "gradlew jar" (which builds the :server jar and bundles it) and copies the
    newest *-server.jar from build\libs into the deploy folder. The deploy
    folder is created when missing. Exits non-zero when the build fails or no
    jar is produced.

.PARAMETER Clean
    Run "gradlew clean" before building.

.PARAMETER DryRun
    Print what would be deleted, run and copied without doing it.

.EXAMPLE
    PS> .\scripts\build-deploy.ps1
    Builds and deploys the jar.

.EXAMPLE
    PS> .\scripts\build-deploy.ps1 -Clean
    Runs gradlew clean first, then builds and deploys.

.EXAMPLE
    PS> .\scripts\build-deploy.ps1 -Clean -DryRun
    Shows the full clean build and deploy plan without running it.
#>
[CmdletBinding()]
param(
    [switch]$Clean,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$deploy = Join-Path $root 'deploy'
$libs = Join-Path $root 'build\libs'
$gradlew = Join-Path $root 'gradlew.bat'
. (Join-Path $PSScriptRoot 'lib\JavaHome.ps1')

function Invoke-Gradle([string[]]$GradleArgs) {
    Write-Host "> gradlew $($GradleArgs -join ' ')" -ForegroundColor Cyan
    if ($DryRun) { return }
    # fabric-loom needs Gradle itself to run on Java 25+, not only the toolchain.
    $null = Use-SilkPaperJdk
    Push-Location $root
    try {
        & $gradlew @GradleArgs
        if ($LASTEXITCODE -ne 0) { throw "gradlew $($GradleArgs -join ' ') failed with exit code $LASTEXITCODE" }
    } finally {
        Pop-Location
    }
}

try {
    if (-not (Test-Path $deploy)) {
        Write-Host "Creating $deploy"
        if (-not $DryRun) { New-Item -ItemType Directory -Path $deploy | Out-Null }
    }

    # Deployed jars are build output and are regenerated by this script.
    $oldJars = @(Get-ChildItem -Path $deploy -Filter '*.jar' -File -ErrorAction SilentlyContinue)
    foreach ($jar in $oldJars) {
        Write-Host "Removing $($jar.FullName)"
        if (-not $DryRun) { Remove-Item -LiteralPath $jar.FullName -Force }
    }

    $buildStart = Get-Date
    if ($Clean) { Invoke-Gradle @('clean') }
    Invoke-Gradle @('jar')

    if ($DryRun) {
        Write-Host "Would copy the newest *-server.jar from $libs to $deploy"
        exit 0
    }

    # The jar name carries the git commit id (silkard-<mc>-<commit>-server.jar),
    # so pick the newest one rather than a fixed name.
    $jar = Get-ChildItem -Path $libs -Filter '*-server.jar' -File -ErrorAction SilentlyContinue |
        Sort-Object LastWriteTime -Descending | Select-Object -First 1
    if (-not $jar) { throw "No *-server.jar found in $libs" }
    if ($jar.LastWriteTime -lt $buildStart) {
        Write-Warning "$($jar.Name) is older than this build; Gradle may have reused a cached output."
    }

    Copy-Item -LiteralPath $jar.FullName -Destination $deploy -Force
    Write-Host "Deployed $(Join-Path $deploy $jar.Name)" -ForegroundColor Green
    exit 0
} catch {
    Write-Error $_
    exit 1
}
